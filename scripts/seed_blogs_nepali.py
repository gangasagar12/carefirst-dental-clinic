def seed_all_nepali_blogs():
    print("=" * 60)
    print("SEEDING HIGH-ACCURACY NEPALI BLOG TRANSLATIONS")
    print("=" * 60)

    for post in BlogPost.objects.all():
        slug_lower = (post.slug or "").lower()
        title_lower = (post.title or "").lower()
        matched = False

        for key, data in BLOG_TRANSLATIONS.items():
            if key in slug_lower or key.replace('-', ' ') in title_lower or any(w in title_lower for w in key.split('-') if len(w) > 4):
                safe_update_model(
                    BlogPost.objects.filter(id=post.id),
                    title_en=post.title,
                    title_ne=data["title_ne"],
                    excerpt_en=post.excerpt,
                    excerpt_ne=data["excerpt_ne"],
                    content_en=post.content,
                    content_ne=data["content_ne"],
                    reading_time_en=post.reading_time or "5 min read",
                    reading_time_ne=data.get("reading_time_ne", "५ मिनेटको पढाइ")
                )
                print(f"[MATCHED BLOG] {post.title[:45]} -> {data['title_ne'][:45]}")
                matched = True
                break

        if not matched:
            # Fallback auto-translation
            t_ne = translate_to_nepali(post.title)
            e_ne = translate_to_nepali(post.excerpt or "")
            c_ne = translate_to_nepali(post.content or "")
            safe_update_model(
                BlogPost.objects.filter(id=post.id),
                title_en=post.title,
                title_ne=t_ne,
                excerpt_en=post.excerpt,
                excerpt_ne=e_ne,
                content_en=post.content,
                content_ne=c_ne
            )
            print(f"[AUTO-TRANSLATED BLOG] {post.title[:45]} -> {t_ne[:45]}")

    # Also translate categories
    cat_map = {
        "general": "साधारण दन्त चिकित्सा",
        "implant": "डेन्टल इम्प्लान्ट",
        "root": "रूट क्यानल उपचार",
        "orthodont": "तार बाँध्ने उपचार (अर्थोडोन्टिक्स / ब्रेसेस)",
        "gum": "गिजाको उपचार",
        "hygiene": "मुखको सरसफाइ",
        "cosmetic": "कस्मेटिक दन्त चिकित्सा",
        "pediatric": "बाल दन्त चिकित्सा"
    }
    for cat in BlogCategory.objects.all():
        name_lower = cat.name.lower()
        for k, ne_val in cat_map.items():
            if k in name_lower:
                safe_update_model(
                    BlogCategory.objects.filter(id=cat.id),
                    name_en=cat.name,
                    name_ne=ne_val
                )
                print(f"[BLOG CATEGORY] {cat.name} -> {ne_val}")
                break

    print("\nALL BLOG POSTS & CATEGORIES FULLY TRANSLATED IN NEPALI!")

if __name__ == '__main__':
    seed_all_nepali_blogs()
