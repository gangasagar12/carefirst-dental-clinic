def update_faqs():
    with connection.cursor() as cursor:
        # First ensure question_en and answer_en have base values if empty
        cursor.execute("UPDATE main_seofaq SET question_en = question WHERE question_en IS NULL OR question_en = ''")
        cursor.execute("UPDATE main_seofaq SET answer_en = answer WHERE answer_en IS NULL OR answer_en = ''")
    
    for faq in SEOFAQ.objects.all():
        q_en = faq.question_en or faq.question
        if q_en in FAQ_TRANSLATIONS:
            t = FAQ_TRANSLATIONS[q_en]
            faq.question_en = q_en
            faq.question_ne = t["q_ne"]
            if not faq.answer_en:
                faq.answer_en = faq.answer
            faq.answer_ne = t["a_ne"]
            faq.save()
            print(f"Updated FAQ ID {faq.id}: {q_en} -> {t['q_ne']}")
        else:
            print(f"No custom translation for: {q_en}")

    # Category translations
    cat_translations = {
        "dental-implants": ("डेन्टल इम्प्लान्ट (दाँत प्रत्यारोपण)", "नेपालमा डेन्टल इम्प्लान्टको लागत, विधि र स्थायित्वसम्बन्धी प्रश्नोत्तर।"),
        "root-canal": ("रूट क्यानल उपचार (RCT)", "रूट क्यानल उपचार प्रक्रिया र शुल्कसम्बन्धी बारम्बार सोधिने प्रश्नहरू।"),
        "orthodontics": ("अर्थोडोन्टिक्स (ब्रेसेस / तार बाँध्ने)", "ब्रेसेस, क्लियर अलाइनर र उपचार सम्बन्धी प्रश्नोत्तर।"),
        "local-seo": ("सामान्य तथा क्लिनिकल जानकारी", "काठमाडौँमा क्लिनिकको स्थान, समय, विशेषज्ञ डाक्टर र सुविधाहरू।")
    }

    for cat in SEOFAQCategory.objects.all():
        if cat.slug in cat_translations:
            name_ne, desc_ne = cat_translations[cat.slug]
            cat.name_en = cat.name
            cat.name_ne = name_ne
            cat.description_en = cat.description or ""
            cat.description_ne = desc_ne
            cat.save()
            print(f"Updated Category: {cat.slug} -> {name_ne}")

